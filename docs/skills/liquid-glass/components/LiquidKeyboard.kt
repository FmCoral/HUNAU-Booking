@Composable
fun LiquidKeyboard(
    backdrop: Backdrop,
    isDark: Boolean,
    onKeyInput: (String) -> Unit,
    onBackspace: () -> Unit,
    onCloseKeyboard: () -> Unit,
    modifier: Modifier = Modifier
) {
    var keyboardMode by remember { mutableStateOf(LiquidKeyboardMode.Pinyin26Key) }
    var showSwitchMenu by remember { mutableStateOf(false) }

    var pinyinBuffer by remember { mutableStateOf("") }
    var t9DigitsBuffer by remember { mutableStateOf("") }
    var isShifted by remember { mutableStateOf(false) }

    val keyboardBackdrop = rememberLayerBackdrop()
    val animScope = rememberCoroutineScope()

    val keyboardPressAnim = remember { Animatable(0f) }
    val triggerKeyboardPulse: () -> Unit = {
        animScope.launch {
            keyboardPressAnim.animateTo(1f, spring(0.55f, 400f))
            keyboardPressAnim.animateTo(0f, spring(0.70f, 300f))
        }
    }

    // ── 长按连续快速删除逻辑 (Continuous Rapid Backspace Engine) ────────────────
    var isBackspaceHeld by remember { mutableStateOf(false) }
    LaunchedEffect(isBackspaceHeld) {
        if (isBackspaceHeld) {
            triggerKeyboardPulse()
            if (keyboardMode == LiquidKeyboardMode.Pinyin9Key && t9DigitsBuffer.isNotEmpty()) {
                t9DigitsBuffer = t9DigitsBuffer.dropLast(1)
            } else if (pinyinBuffer.isNotEmpty()) {
                pinyinBuffer = pinyinBuffer.dropLast(1)
            } else {
                onBackspace()
            }
            delay(350)
            while (isBackspaceHeld) {
                if (keyboardMode == LiquidKeyboardMode.Pinyin9Key && t9DigitsBuffer.isNotEmpty()) {
                    t9DigitsBuffer = t9DigitsBuffer.dropLast(1)
                } else if (pinyinBuffer.isNotEmpty()) {
                    pinyinBuffer = pinyinBuffer.dropLast(1)
                } else {
                    onBackspace()
                }
                delay(70) // 每 70ms 连续高频回删
            }
        }
    }

    val panelSurface = if (isDark) Color(0xFF0A0A1C).copy(alpha = 0.40f)
    else Color(0xFFF0F2F8).copy(alpha = 0.40f)

    val slideAnim = remember { Animatable(100f) }
    val alphaAnim = remember { Animatable(0f) }
    LaunchedEffect(Unit) {
        launch { slideAnim.animateTo(0f, spring(0.7f, 350f)) }
        launch { alphaAnim.animateTo(1f, spring(0.7f, 350f)) }
    }

    Box(
        modifier.graphicsLayer {
            translationY = slideAnim.value
            alpha = alphaAnim.value
            transformOrigin = TransformOrigin(0.5f, 1f)
