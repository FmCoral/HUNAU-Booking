@Composable
private fun LiquidKeyboardPopupMenu(
    backdrop: Backdrop,
    currentMode: LiquidKeyboardMode,
    isDark: Boolean,
    onSelectMode: (LiquidKeyboardMode) -> Unit,
    onDismiss: () -> Unit
) {
    val menuBackdrop = rememberLayerBackdrop()

    val containerSurface = if (isDark) Color(0xFF04040E).copy(alpha = 0.40f)
    else Color(0xFFFFFFFF).copy(alpha = 0.40f)
    val textColor = if (isDark) Color.White else Color(0xFF1A1A2E)
    val modes = LiquidKeyboardMode.values()
    val itemCount = modes.size

    // 入场动画（scale + alpha）
    val scaleAnim = remember { Animatable(0.75f) }
    val alphaAnim = remember { Animatable(0f) }
    LaunchedEffect(Unit) {
        launch { scaleAnim.animateTo(1f, spring(0.55f, 380f, 0.001f)) }
        launch { alphaAnim.animateTo(1f, spring(0.55f, 380f, 0.001f)) }
    }

    BoxWithConstraints(
        Modifier
            .graphicsLayer { alpha = alphaAnim.value }
            .width(60.dp)
            .height(48.dp * itemCount + 8.dp),
        contentAlignment = Alignment.TopStart
    ) {
        val density = LocalDensity.current
        val itemHeight = with(density) {
            (constraints.maxHeight.toFloat() - 8f.dp.toPx()) / itemCount
        }
        val animationScope = rememberCoroutineScope()

        // 阻尼弹簧滑动动画（指示器在项间垂直弹簧滑动 + 按压缩放）
        val dampedDragAnimation = remember(animationScope) {
            DampedDragAnimation(
                animationScope = animationScope,
                initialValue = modes.indexOf(currentMode).toFloat(),
                valueRange = 0f..(itemCount - 1).toFloat(),
                visibilityThreshold = 0.001f,
                initialScale = 1f,
                pressedScale = 1.15f,
                onDragStarted = {},
                onDragStopped = {
                    val targetIndex = targetValue.fastRoundToInt().fastCoerceIn(0, itemCount - 1)
                    animateToValue(targetIndex.toFloat())
                    animationScope.launch {
                        delay(200)
                        onSelectMode(modes[targetIndex])
                    }
                },
                onDrag = { _, dragAmount ->
                    updateValue(
                        (targetValue + dragAmount.y / itemHeight)
                            .fastCoerceIn(0f, (itemCount - 1).toFloat())
                    )
                }
            )
        }

        // 交互式高光（跟随手指位置的动态玻璃高光，垂直方向）
        val interactiveHighlight = remember(animationScope) {
            InteractiveHighlight(
                animationScope = animationScope,
                position = { size, _ ->
                    Offset(
                        size.width / 2f,
                        (dampedDragAnimation.value + 0.5f) * itemHeight
                    )
                }
            )
        }

        // 当前指示器所在项索引（用于文字颜色 / 字重）
        val activeIndex by remember {
            derivedStateOf {
                dampedDragAnimation.value.fastRoundToInt().fastCoerceIn(0, itemCount - 1)
            }
        }

        // 选中项动画（与 LiquidBottomTabs 完全一致的 press / animateToValue / release 模式）
        val selectItem: (Int) -> Unit = remember(dampedDragAnimation) {
            { index ->
                dampedDragAnimation.press()
                dampedDragAnimation.animateToValue(index.toFloat())
                animationScope.launch {
                    dampedDragAnimation.release()
                    delay(200)
                    onSelectMode(modes[index])
                }
            }
        }

        // Layer 1: 玻璃面板底座（导出到 menuBackdrop，供指示器复用）
        Box(
            Modifier
                .drawBackdrop(
                    backdrop = backdrop,
                    exportedBackdrop = menuBackdrop,
                    shape = { RoundedCornerShape(20.dp) },
                    effects = {
                        vibrancy()
                        blur(8f.dp.toPx())
                        lens(24f.dp.toPx(), 24f.dp.toPx(), chromaticAberration = false)
                    },
                    layerBlock = {
                        scaleX = scaleAnim.value
                        scaleY = scaleAnim.value
                        transformOrigin = TransformOrigin(0.85f, 1f)
                    },
                    onDrawSurface = { drawRect(containerSurface) }
                )
                .fillMaxWidth()
                .fillMaxHeight()
        )

        // Layer 2: 玻璃滑动指示器（胶囊形，全玻璃效果 — 下方文字在 Layer 3 不受遮挡）
        Box(
            Modifier
                .padding(4.dp)
                .graphicsLayer {
                    translationY = dampedDragAnimation.value * itemHeight
                }
                .drawBackdrop(
                    backdrop = rememberCombinedBackdrop(backdrop, menuBackdrop),
                    shape = { Capsule() },
                    effects = {
                        val progress = dampedDragAnimation.pressProgress
                        lens(
                            10f.dp.toPx() * progress,
                            14f.dp.toPx() * progress,
                            chromaticAberration = true
                        )
                    },
                    highlight = {
                        Highlight.Default.copy(alpha = dampedDragAnimation.pressProgress)
                    },
                    shadow = {
                        Shadow(alpha = dampedDragAnimation.pressProgress)
                    },
                    innerShadow = {
                        InnerShadow(
                            radius = 8f.dp * dampedDragAnimation.pressProgress,
                            alpha = dampedDragAnimation.pressProgress
                        )
                    },
                    layerBlock = {
                        scaleX = dampedDragAnimation.scaleX
                        scaleY = dampedDragAnimation.scaleY
                        val velocity = dampedDragAnimation.velocity / 10f
                        scaleX /= 1f - (velocity * 0.75f).fastCoerceIn(-0.2f, 0.2f)
                        scaleY *= 1f - (velocity * 0.25f).fastCoerceIn(-0.2f, 0.2f)
                    },
                    onDrawSurface = {
                        val progress = dampedDragAnimation.pressProgress
                        drawRect(
                            if (isDark) Color.White.copy(alpha = 0.03f)
                            else Color.Black.copy(alpha = 0.03f),
                            alpha = 1f - progress * 0.7f
                        )
                    }
                )
                .fillMaxWidth()
                .fillMaxHeight(1f / itemCount)
        )

        // Layer 3: 输入法模式文字（始终在最上层）
        // 拖动手势也在此层处理
        Column(
            Modifier
                .then(interactiveHighlight.gestureModifier)
                .then(dampedDragAnimation.modifier)
                .then(interactiveHighlight.modifier)
                .fillMaxWidth()
                .fillMaxHeight()
                .padding(4.dp),
            verticalArrangement = Arrangement.spacedBy(0.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            modes.forEachIndexed { index, mode ->
                val isSelected = index == activeIndex
                Box(
                    Modifier
                        .weight(1f)
                        .fillMaxWidth()
                        .clickable(interactionSource = null, indication = null) {
                            selectItem(index)
                        },
                    contentAlignment = Alignment.Center
                ) {
                    BasicText(
                        mode.label,
                        style = TextStyle(
                            color = textColor,
                            fontSize = 14.sp,
                            fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Medium
                        )
                    )
                }
            }
        }
    }
}

