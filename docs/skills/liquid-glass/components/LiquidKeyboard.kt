                    backdrop = backdrop,
                    exportedBackdrop = keyboardBackdrop,
                    shape = { RoundedCornerShape(28.dp) },
                    effects = {
                        val kp = keyboardPressAnim.value
                        vibrancy()
                        blur(20f.dp.toPx())
                        lens(
                            (20f + 6f * kp).dp.toPx(),
                            (24f + 8f * kp).dp.toPx(),
                            chromaticAberration = true
                        )
                    },
                    layerBlock = {
                        val kp = keyboardPressAnim.value
                        val kScale = lerp(1f, 1.025f, kp)
                        scaleX = kScale
                        scaleY = kScale
                    },
                    highlight = { Highlight.Default.copy(alpha = 0.18f + 0.12f * keyboardPressAnim.value) },
                    shadow = { Shadow(radius = 24f.dp, alpha = 0.18f) },
                    innerShadow = { InnerShadow(radius = 6f.dp, alpha = 0.08f) },
                    onDrawSurface = { drawRect(panelSurface) }
                )
                .padding(horizontal = 8.dp, vertical = 10.dp),
            verticalArrangement = Arrangement.spacedBy(8.dp)
        ) {

            // ── 拼音置顶于候选词上方的精美双层结构 (Stacked Pinyin & Candidate Bar) ────────
            val activePinyin = if (keyboardMode == LiquidKeyboardMode.Pinyin9Key && t9DigitsBuffer.isNotEmpty()) {
                val resolvedList = resolveT9Pinyin(t9DigitsBuffer)
                resolvedList.firstOrNull() ?: t9DigitsBuffer
            } else {
                pinyinBuffer
            }

            if (activePinyin.isNotEmpty()) {
                val candidateResult = getPinyinCandidateResult(activePinyin)
                Column(
                    Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 6.dp)
                ) {
                    BasicText(
                        candidateResult.formattedPinyin,
                        style = TextStyle(
                            color = if (isDark) Color(0xFF0088FF) else Color(0xFF0066CC),
                            fontSize = 12.sp,
                            fontWeight = FontWeight.Bold
                        ),
                        modifier = Modifier.padding(bottom = 2.dp)
                    )

                    Row(
                        Modifier
                            .fillMaxWidth()
                            .height(36.dp)
                            .horizontalScroll(rememberScrollState()),
                        horizontalArrangement = Arrangement.spacedBy(8.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        candidateResult.candidates.forEach { candidate ->
                            Box(
                                Modifier
                                    .clickable {
                                        triggerKeyboardPulse()
                                        onKeyInput(candidate.text)
                                        if (keyboardMode == LiquidKeyboardMode.Pinyin9Key) {
                                            t9DigitsBuffer = ""
                                            pinyinBuffer = ""
                                        } else {
                                            pinyinBuffer = consumePinyinSyllables(pinyinBuffer, candidate.consumedSyllablesCount)
                                        }
                                    }
                                    .padding(horizontal = 10.dp, vertical = 4.dp)
                            ) {
                                BasicText(
                                    candidate.text,
                                    style = TextStyle(
                                        color = if (isDark) Color.White else Color(0xFF1A1A2E),
                                        fontSize = 16.sp,
                                        fontWeight = FontWeight.Medium
                                    )
                                )
                            }
                        }
                    }
                }
            }

            when (keyboardMode) {
                LiquidKeyboardMode.Pinyin9Key -> {
                    Liquid9KeyGrid(
                        backdrop = keyboardBackdrop,
                        isDark = isDark,
                        onDigitPress = { digit ->
                            triggerKeyboardPulse()
                            t9DigitsBuffer += digit
