                shadow = {
                    val p = hl.pressProgress
                    Shadow(radius = 8f.dp, alpha = 0.08f + 0.15f * p)
                },
                innerShadow = {
                    val p = hl.pressProgress
                    InnerShadow(radius = 4f.dp * p, alpha = 0.15f * p)
                },
                onDrawSurface = { drawRect(keySurface) }
            )
            .then(hl.modifier)
            .then(hl.gestureModifier)
            .pointerInput(Unit) {
                detectTapGestures(
                    onPress = {
                        onPressStateChange(true)
                        tryAwaitRelease()
                        onPressStateChange(false)
                    }
                )
            },
        contentAlignment = Alignment.Center
    ) {
        BasicText(
            text,
            style = TextStyle(
                color = textColor,
                fontSize = if (text.length > 3) 12.sp else 16.sp,
                fontWeight = FontWeight.Medium
            )
        )
    }
