private fun pinyinToT9Digits(py: String): String {
    val letterToDigit = mapOf(
        'a' to '2', 'b' to '2', 'c' to '2',
        'd' to '3', 'e' to '3', 'f' to '3',
        'g' to '4', 'h' to '4', 'i' to '4',
        'j' to '5', 'k' to '5', 'l' to '5',
        'm' to '6', 'n' to '6', 'o' to '6',
        'p' to '7', 'q' to '7', 'r' to '7', 's' to '7',
        't' to '8', 'u' to '8', 'v' to '8',
        'w' to '9', 'x' to '9', 'y' to '9', 'z' to '9'
    )
    return py.lowercase().map { letterToDigit[it] ?: it }.joinToString("")
}

private val T9_PINYIN_MAP: Map<String, List<String>> by lazy {
    val map = mutableMapOf<String, MutableList<String>>()
    ALL_SYLLABLES.forEach { syl ->
        val digits = pinyinToT9Digits(syl)
        map.getOrPut(digits) { mutableListOf() }.add(syl)
    }
    map
}

private fun resolveT9Pinyin(digits: String): List<String> {
    if (digits.isEmpty()) return emptyList()
    val cleanDigits = digits.filter { it.isDigit() }
    val result = mutableListOf<String>()

    MASTER_LEXICON.forEach { entry ->
        val initialDigits = pinyinToT9Digits(entry.initial)
        val fullDigits = pinyinToT9Digits(entry.pinyin)
        if (initialDigits == cleanDigits || fullDigits == cleanDigits || initialDigits.startsWith(cleanDigits) || fullDigits.startsWith(cleanDigits)) {
            result.add(entry.word)
        }
    }

    T9_PINYIN_MAP[cleanDigits]?.let { result.addAll(it) }

    if (result.isEmpty()) {
        result.add(cleanDigits)
    }
    return result.distinct()
}

private fun segmentPinyin(py: String): List<String> {
    if (py.isEmpty()) return emptyList()
    val result = mutableListOf<String>()
    var rem = py.lowercase().trim()
    while (rem.isNotEmpty()) {
        var matched = false
        for (len in rem.length downTo 1) {
            val sub = rem.substring(0, len)
            if (ALL_SYLLABLES.contains(sub)) {
                result.add(sub)
                rem = rem.substring(len)
                matched = true
                break
            }
        }
        if (!matched) {
            result.add(rem.substring(0, 1))
            rem = rem.substring(1)
        }
    }
    return result
}

private fun consumePinyinSyllables(py: String, count: Int): String {
    val syllables = segmentPinyin(py)
    if (count >= syllables.size) return ""
    return syllables.drop(count).joinToString("")
}

private data class PinyinCandidateResult(
    val formattedPinyin: String,
    val candidates: List<PinyinCandidateItem>
)

private data class PinyinCandidateItem(
    val text: String,
    val consumedSyllablesCount: Int
)

private fun getPinyinCandidateResult(py: String): PinyinCandidateResult {
    val cleanPy = py.lowercase().trim()
    if (cleanPy.isEmpty()) return PinyinCandidateResult("", emptyList())

    val itemList = mutableListOf<PinyinCandidateItem>()

    // 1. 查询 10万+ 级开源词典引擎 (PinyinLexiconEngine)
    val lexiconHits = PinyinLexiconEngine.queryCandidates(cleanPy)
    lexiconHits.forEach { (word, consumed) ->
        if (itemList.none { it.text == word }) {
            itemList.add(PinyinCandidateItem(word, consumed))
        }
    }

    // 2. 全词库前缀/全拼/简拼深度匹配 (不限字数，支持2/3/4/5+长词及全音节组合)
    MASTER_LEXICON.forEach { entry ->
        if (entry.initial.startsWith(cleanPy) || entry.pinyin.startsWith(cleanPy) || entry.initial == cleanPy || entry.pinyin == cleanPy) {
            if (itemList.none { it.text == entry.word }) {
                val consumedCount = if (cleanPy.length <= entry.initial.length) cleanPy.length else segmentPinyin(cleanPy).size
                itemList.add(PinyinCandidateItem(entry.word, consumedCount))
            }
        }
    }

    // 2. 多音节拆解与常用单字推演
    val syllables = segmentPinyin(cleanPy)
    val formattedPy = syllables.joinToString("'")

    val firstSyl = syllables.firstOrNull() ?: ""
    val singleChars = SYLLABLE_CHAR_MAP[firstSyl] ?: listOf(firstSyl)
    singleChars.forEach { char ->
        if (itemList.none { it.text == char }) {
            itemList.add(PinyinCandidateItem(char, 1))
        }
    }

    return PinyinCandidateResult(formattedPy, itemList)
}

